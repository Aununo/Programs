// 轮常量 (Round Constant)
const unsigned char r_con[] = {
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 
    0x80, 0x1b, 0x36, 0x6c, 0xd8, 0xab, 0x4d, 0x9a};

// 轮密钥加 (AddRoundKey)
void add_round_key(state_t& state, const unsigned char round_key[4][4]) {
    for (int r = 0; r < 4; ++r) {
        for (int c = 0; c < 4; ++c) {
            state[r][c] ^= round_key[r][c];
        }
    }
}

// 字节替换 (SubBytes)
void sub_bytes(state_t& state) {
    for (int r = 0; r < 4; ++r) {
        for (int c = 0; c < 4; ++c) {
            state[r][c] = s_box[state[r][c]];
        }
    }
}

// 逆字节替换 (InvSubBytes)
void inv_sub_bytes(state_t& state) {
    for (int r = 0; r < 4; ++r) {
        for (int c = 0; c < 4; ++c) {
            state[r][c] = inv_s_box[state[r][c]];
        }
    }
}

// 行移位 (ShiftRows)
void shift_rows(state_t& state) {
    // Row 1: left shift by 1
    unsigned char temp = state[1][0];
    state[1][0] = state[1][1];
    state[1][1] = state[1][2];
    state[1][2] = state[1][3];
    state[1][3] = temp;

    // Row 2: left shift by 2
    temp = state[2][0];
    state[2][0] = state[2][2];
    state[2][2] = temp;
    temp = state[2][1];
    state[2][1] = state[2][3];
    state[2][3] = temp;

    // Row 3: left shift by 3 (equivalent to right shift by 1)
    temp = state[3][0];
    state[3][0] = state[3][1];
    state[3][1] = state[3][2];
    state[3][2] = state[3][3];
    state[3][3] = temp;
}

// 逆行移位 (InvShiftRows)
void inv_shift_rows(state_t& state) {
    // Row 1: right shift by 1
    unsigned char temp = state[1][3];
    state[1][3] = state[1][2];
    state[1][2] = state[1][1];
    state[1][1] = state[1][0];
    state[1][0] = temp;
    
    // Row 2: right shift by 2
    temp = state[2][0];
    state[2][0] = state[2][2];
    state[2][2] = temp;
    temp = state[2][1];
    state[2][1] = state[2][3];
    state[2][3] = temp;
    
    // Row 3: right shift by 3 (equivalent to left shift by 1)
    temp = state[3][3];
    state[3][3] = state[3][2];
    state[3][2] = state[3][1];
    state[3][1] = state[3][0];
    state[3][0] = temp;
}

// GF(2^8)下的乘2运算 (xtime)
unsigned char xtime(unsigned char x) {
    return (x & 0x80) ? ((x << 1) ^ 0x1b) : (x << 1);
}

// 列混淆 (MixColumns)
void mix_columns(state_t& state) {
    for (int c = 0; c < 4; ++c) {
        unsigned char a = state[0][c];
        unsigned char b = state[1][c];
        unsigned char d = state[2][c];
        unsigned char e = state[3][c];
        unsigned char t = a ^ b ^ d ^ e;
        unsigned char u = a;
        state[0][c] ^= t ^ xtime(a ^ b);
        state[1][c] ^= t ^ xtime(b ^ d);
        state[2][c] ^= t ^ xtime(d ^ e);
        state[3][c] ^= t ^ xtime(e ^ u);
    }
}

// 逆列混淆 (InvMixColumns)
void inv_mix_columns(state_t& state) {
    for (int c = 0; c < 4; ++c) {
        unsigned char a = state[0][c];
        unsigned char b = state[1][c];
        unsigned char d = state[2][c];
        unsigned char e = state[3][c];
        unsigned char u = xtime(xtime(a ^ d));
        unsigned char v = xtime(xtime(b ^ e));
        state[0][c] ^= u;
        state[1][c] ^= v;
        state[2][c] ^= u;
        state[3][c] ^= v;
    }
    mix_columns(state);
}

// 密钥扩展 (Key Expansion)
void expand_key(const std::vector<unsigned char>& master_key, unsigned char expanded_keys[N_ROUNDS + 1][4][4]) {
    if (master_key.size() != 16) {
        throw std::invalid_argument("Key must be 16 bytes for AES-128.");
    }
    
    const int Nk = 4; // Nk = 4 for AES-128
    const int Nb = 4; // Nb = 4 (block size in words)
    
    std::vector<std::vector<unsigned char>> w(Nb * (N_ROUNDS + 1), std::vector<unsigned char>(4));

    for (int i = 0; i < Nk; ++i) {
        w[i][0] = master_key[4 * i + 0];
        w[i][1] = master_key[4 * i + 1];
        w[i][2] = master_key[4 * i + 2];
        w[i][3] = master_key[4 * i + 3];
    }
    
    for (int i = Nk; i < Nb * (N_ROUNDS + 1); ++i) {
        std::vector<unsigned char> temp = w[i - 1];
        if (i % Nk == 0) {
            // RotWord: 循环左移一个字节
            unsigned char first_byte = temp[0];
            temp.erase(temp.begin());
            temp.push_back(first_byte);
            
            // SubWord: S-盒字节替换
            for (int j = 0; j < 4; ++j) {
                temp[j] = s_box[temp[j]];
            }

            // 与轮常量异或
            temp[0] ^= r_con[i / Nk];
        }
        for (int j = 0; j < 4; ++j) {
            w[i][j] = w[i - Nk][j] ^ temp[j];
        }
    }
    
    // 将扩展后的密钥w转换为 [轮数][4][4] 的格式，方便使用
    for (int r = 0; r < N_ROUNDS + 1; ++r) {
        for (int c = 0; c < 4; ++c) {
            for (int row = 0; row < 4; ++row) {
                expanded_keys[r][row][c] = w[r * Nb + c][row];
            }
        }
    }
}


// 核心加密函数
std::vector<unsigned char> encrypt(const std::vector<unsigned char>& plaintext, const std::vector<unsigned char>& key) {
    if (plaintext.size() != 16) throw std::invalid_argument("Plaintext block must be 16 bytes.");

    unsigned char round_keys[N_ROUNDS + 1][4][4];
    expand_key(key, round_keys);

    state_t state;
    // 将1D明文块按列主序映射到2D状态矩阵
    for(int r = 0; r < 4; ++r) {
        for (int c = 0; c < 4; ++c) {
            state[r][c] = plaintext[c * 4 + r];
        }
    }

    // 初始轮密钥加
    add_round_key(state, round_keys[0]);

    // 主要的 N_ROUNDS - 1 轮
    for (int i = 1; i < N_ROUNDS; ++i) {
        sub_bytes(state);
        shift_rows(state);
        mix_columns(state);
        add_round_key(state, round_keys[i]);
    }
    
    // 最后一轮 (无 MixColumns)
    sub_bytes(state);
    shift_rows(state);
    add_round_key(state, round_keys[N_ROUNDS]);

    // 将最终状态按列主序转换回1D密文块
    std::vector<unsigned char> ciphertext(16);
    for(int r = 0; r < 4; ++r) {
        for (int c = 0; c < 4; ++c) {
            ciphertext[c * 4 + r] = state[r][c];
        }
    }
    return ciphertext;
}

std::vector<unsigned char> decrypt(const std::vector<unsigned char>& ciphertext, const std::vector<unsigned char>& key) {
    if (ciphertext.size() != 16) throw std::invalid_argument("Ciphertext block must be 16 bytes.");

    unsigned char round_keys[N_ROUNDS + 1][4][4];
    expand_key(key, round_keys);
    
    state_t state;
    for(int r = 0; r < 4; ++r) {
        for (int c = 0; c < 4; ++c) {
            state[r][c] = ciphertext[c * 4 + r];
        }
    }
    
    // 初始轮 (使用最后一轮的密钥)
    add_round_key(state, round_keys[N_ROUNDS]);

    // 主要的 N_ROUNDS - 1 轮 (逆序)
    for (int i = N_ROUNDS - 1; i > 0; --i) {
        inv_shift_rows(state);
        inv_sub_bytes(state);
        add_round_key(state, round_keys[i]);
        inv_mix_columns(state);
    }
    
    // 最后一轮 (无 InvMixColumns)
    inv_shift_rows(state);
    inv_sub_bytes(state);
    add_round_key(state, round_keys[0]);

    // 将最终状态按列主序转换回1D明文块
    std::vector<unsigned char> plaintext(16);
    for(int r = 0; r < 4; ++r) {
        for (int c = 0; c < 4; ++c) {
            plaintext[c * 4 + r] = state[r][c];
        }
    }
    return plaintext;
}


